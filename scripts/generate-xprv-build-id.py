#!/usr/bin/env python3
"""Generate xprv-build-id.cpp from the current tracked Git snapshot.

Identity (for /health build_id):
  clean:  <short-head>
  dirty:  <short-head>-dirty.<hash8 of `git diff --binary HEAD`>

The binary patch covers staged and unstaged changes to tracked files without
decoding their contents. Untracked files are intentionally out of scope: they
are not part of the Git snapshot named by HEAD.

Only rewrites the output when contents change so a single TU recompiles.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import subprocess
import sys
from pathlib import Path

# short head, optional -dirty.<hash8>, or unknown
SAFE_ID = re.compile(r"^[0-9a-zA-Z._-]+$")


def git(repo: Path, *args: str) -> tuple[int, bytes]:
    try:
        completed = subprocess.run(
            ["git", *args],
            cwd=repo,
            capture_output=True,
            check=False,
        )
    except FileNotFoundError:
        return 127, b""
    return completed.returncode, completed.stdout


def resolve_id(repo: Path) -> str:
    code, inside = git(repo, "rev-parse", "--is-inside-work-tree")
    if code != 0 or inside.strip() != b"true":
        return "unknown"

    code, head = git(repo, "rev-parse", "--short", "HEAD")
    if code != 0 or not head.strip():
        return "unknown"
    try:
        head_text = head.strip().decode("ascii")
    except UnicodeDecodeError:
        return "unknown"

    # Staged + unstaged vs HEAD for tracked paths. --binary makes the digest
    # content-sensitive for binary files and keeps the subprocess byte-safe.
    code, diff = git(
        repo,
        "diff",
        "--binary",
        "--no-ext-diff",
        "--no-textconv",
        "HEAD",
        "--",
    )
    if code != 0:
        return f"{head_text}-dirty.unknown"
    if not diff:
        return head_text

    digest = hashlib.sha256(diff).hexdigest()[:8]
    return f"{head_text}-dirty.{digest}"


def render_cpp(build_id: str) -> str:
    if not SAFE_ID.fullmatch(build_id):
        raise SystemExit(f"refusing unsafe build id: {build_id!r}")
    return (
        "// Auto-generated by scripts/generate-xprv-build-id.py — do not edit.\n"
        "#include <xprv/build-id.h>\n"
        "\n"
        "namespace xprv {\n"
        "\n"
        "std::string_view\n"
        "xprv_build_id() noexcept\n"
        "{\n"
        f'    static constexpr char const kId[] = "{build_id}";\n'
        "    return std::string_view{kId, sizeof(kId) - 1};\n"
        "}\n"
        "\n"
        "}  // namespace xprv\n"
    )


def write_if_different(path: Path, content: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    data = content.encode("utf-8")
    if path.is_file():
        try:
            if path.read_bytes() == data:
                return False
        except OSError:
            pass
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_bytes(data)
    os.replace(tmp, path)
    return True


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--repo", type=Path, default=Path.cwd())
    p.add_argument("--output", type=Path, required=True)
    p.add_argument(
        "--config-id",
        default="",
        help="ignored; kept for call-site compatibility",
    )
    p.add_argument("--print-id", action="store_true")
    args = p.parse_args()

    build_id = resolve_id(args.repo.resolve())
    changed = write_if_different(args.output, render_cpp(build_id))
    if args.print_id:
        print(build_id)
        print("updated" if changed else "unchanged", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
