"""Generate deterministic, synthetic signed list-admission witnesses.

No network or production keys. --check compares the committed fixture.
"""
import argparse
import base64
import copy
import importlib.util
import json
from pathlib import Path
import sys


def generate():
    root = Path(__file__).resolve().parents[3]
    spec = importlib.util.spec_from_file_location(
        "trust_fixture_helpers", root / "scripts/test-verify-xprv.py")
    t = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = t
    spec.loader.exec_module(t)

    def fixture(sequence=10):
        f = t.Fixture()
        f.blob_fields.update(sequence=sequence, expiration=0xFFFFFFFF)
        f.voters = f.signers[:4]
        return f

    def validator_case(sequence, signer=None, manifest_sequence=2, **fields):
        f = fixture(sequence)
        f.blob_fields.update(fields)
        if signer is None:
            raw = t.sign_manifest(
                {"PublicKey": f.masters[0][0], "Sequence": 0xFFFFFFFF},
                f.masters[0], None)
        else:
            raw = t.make_manifest(f.masters[0], signer, manifest_sequence)
        f.entries[0]["manifest"] = base64.b64encode(raw).decode()
        return f

    current = fixture()
    cases = {"current": current.anchor()}
    cases["validator_rotation"] = validator_case(9, t.keypair(401)).anchor()
    cases["validator_same_key"] = validator_case(9, current.signers[0]).anchor()
    cases["validator_revoked"] = validator_case(9).anchor()
    cases["validator_conflict"] = validator_case(9, t.keypair(402), 1).anchor()
    cases["validator_higher"] = validator_case(11, t.keypair(403), 3).anchor()
    cases["expired_revocation"] = validator_case(11, expiration=1).anchor()
    cases["pending_revocation"] = validator_case(
        11, effective=0xFFFFFF00).anchor()
    rotated_proof = fixture()
    rotated_proof.voters = [t.keypair(401), *rotated_proof.signers[1:4]]
    cases["rotated_proof"] = rotated_proof.anchor()
    removed = fixture(11)
    removed.entries = removed.entries[1:]
    cases["removed"] = removed.anchor()
    cases["readded"] = fixture(12).anchor()
    unknown = fixture(9)
    unknown_raw = t.make_manifest(t.keypair(109), t.keypair(209), 2)
    unknown.entries.append({"validation_public_key": t.keypair(109)[0],
                            "manifest": base64.b64encode(unknown_raw).decode()})
    cases["unknown"] = unknown.anchor()

    for name, sequence, manifest_sequence, signer in [
        ("publisher_same_key", 9, 2, current.publisher_signing),
        ("publisher_rotation", 9, 2, t.keypair(601)),
        ("publisher_conflict", 10, 1, t.keypair(601)),
        ("publisher_higher", 11, 3, current.publisher_signing),
    ]:
        f = fixture(sequence)
        a = f.anchor(publisher_signing=signer)
        a["unl"]["manifest"] = t.make_manifest(
            f.publisher, signer, manifest_sequence).hex()
        cases[name] = a

    bad_pub = copy.deepcopy(cases["publisher_conflict"])
    raw = bytearray.fromhex(bad_pub["unl"]["manifest"])
    raw[-1] ^= 1
    bad_pub["unl"]["manifest"] = raw.hex()
    cases["invalid_publisher"] = bad_pub
    bad_validator = validator_case(9)
    raw = bytearray(base64.b64decode(bad_validator.entries[0]["manifest"]))
    raw[-1] ^= 1
    bad_validator.entries[0]["manifest"] = base64.b64encode(raw).decode()
    cases["invalid_validator"] = bad_validator.anchor()
    later = {"Flags": 0x80000001, "LedgerSequence": 1001,
             "SigningTime": 800000001, "LedgerHash": "44" * 32,
             "SigningPubKey": current.signers[1][0]}
    signing_data = t.v.PREFIX_VALIDATION + bytes.fromhex(t.encode_for_signing(later))[4:]
    later["Signature"] = t.sign(signing_data, current.signers[1][1])
    return {"description": "Synthetic Ed25519 list admission and conflict witnesses; generated by generate-trust-evidence.py",
            "trusted_key": current.trusted_key, "cases": cases,
            "later_validation": {"raw": t.encode(later), "signing_key": later["SigningPubKey"],
                                 "ledger_hash": later["LedgerHash"], "ledger_seq": 1001}}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    path = Path(__file__).with_name("trust-evidence.json")
    content = json.dumps(generate(), indent=2) + "\n"
    if args.check:
        if path.read_text() != content:
            raise SystemExit("trust-evidence.json is stale")
        print("trust-evidence.json is current")
    else:
        path.write_text(content)
        print(path)


if __name__ == "__main__":
    main()
